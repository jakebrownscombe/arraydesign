test_that("movement_model checks its samplers and switch", {
  st <- function(n) stats::runif(n, 1, 2)
  tu <- function(n) stats::runif(n, -1, 1)
  m <- movement_model(st, tu, source = "test")
  expect_s3_class(m, "movement_model")
  expect_equal(m$states, 1L)
  expect_equal(m$time_step, 60)
  expect_error(movement_model("a", tu), "must be a function")
  expect_error(movement_model(function(n) -st(n), tu), "of at least 0")
  expect_error(movement_model(st, function(n) rep(NA_real_, n)), "5 finite numbers")
  expect_error(movement_model(st, function(n) 1), "5 finite numbers")
  expect_error(movement_model(st, tu, states = 3), "1 or 2")
  expect_error(movement_model(st, tu, transition = diag(2)), "states = 2")
  expect_error(movement_model(st, tu, states = 2), "2 by 2")
  expect_error(movement_model(st, tu, states = 2, transition = matrix(0.4, 2, 2)), "sum to 1")
  expect_error(movement_model(st, tu, states = 2, transition = diag(2)), "absorbing")
  expect_error(movement_model(st, tu, time_step_s = 0), "positive number")
  expect_error(movement_model(st, tu, source = 1), "character string")
})

test_that("print shows the states, the dwell times and the source", {
  m <- crw_model(30, 10, 30, transition = matrix(c(0.95, 0.10, 0.05, 0.90), 2))
  expect_output(print(m), "mean steps in a state: move 20.0, rest 10.0")
  expect_output(print(m), "gamma steps, mean 30 m")
  expect_output(print(movement_model(function(n) rep(1, n), function(n) rep(0, n))),
                "source: not stated")
})

test_that("crw_model draws gamma steps and wrapped normal turns", {
  m <- crw_model(30, 10, 30)
  s <- withr::with_seed(1, m$step(1e5))
  expect_equal(mean(s), 30, tolerance = 0.01)
  expect_equal(stats::sd(s), 10, tolerance = 0.02)
  tn <- withr::with_seed(1, m$turn(1e5))
  expect_true(all(tn >= -pi & tn < pi))
  expect_equal(stats::sd(tn), 30 * pi / 180, tolerance = 0.02)
  u <- withr::with_seed(1, crw_model(30, 10, Inf)$turn(1e5))
  expect_lt(abs(mean(cos(u))), 0.01)
  expect_equal(crw_model(30, 10, 0)$turn(3), c(0, 0, 0))
  expect_error(crw_model(-1, 10, 30), "positive numbers")
  expect_error(crw_model(30, 10, -5), "`turn_sd`")
  expect_equal(crw_model(30, 10, 30, transition = diag(c(0.5, 0.5)) + 0.25)$states, 2L)
})

test_that("evaluate_array() walks by the vignette's correlated random walk by default", {
  m <- withr::with_preserve_seed(evaluation_defaults()$movement)
